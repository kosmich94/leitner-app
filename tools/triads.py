def build_triads(count=76, seed=2027):
    """Κάθε τριάδα παίρνει δηλώσεις από τρεις διαφορετικές δεξιότητες, χωρίς επανάληψη δήλωσης."""
    rng = random.Random(seed)
    pools = {k: rng.sample(v, len(v)) for k, v in SKILLS.items()}
    triads = []
    for _ in range(count):
        ranked = sorted(pools, key=lambda k: (-len(pools[k]), rng.random()))
        picked = [pools[k].pop() for k in ranked[:3]]
        rng.shuffle(picked)
        triads.append(picked)
    assert len({s for t in triads for s in t}) == count * 3
    return triads
