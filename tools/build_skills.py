def norm(text):
    return re.sub(r'\s+', ' ', text).strip()


def read_key(path):
    lines = [l.strip() for l in fitz.open(path)[0].get_text().split('\n') if l.strip()]
    key = {}
    for i, line in enumerate(lines[:-1]):
        m = re.fullmatch(r'(\d+)\.', line)
        if m and lines[i + 1] in LETTERS:
            key[int(m[1])] = LETTERS.index(lines[i + 1])
    assert sorted(key) == list(range(1, 101))
    return key


def read_scenarios(doc):
    text = '\n'.join(p.get_text() for p in doc)
    text = text[text.index('Ακολουθούν είκοσι επτά'):]
    text = re.sub(r'Σελίδα \d+ από 23', '', text).replace('ΤΕΛΟΣ ΕΞΕΤΑΣΗΣ', '')
    found, cur, opt = {}, None, None
    for line in (l.strip() for l in text.split('\n')):
        if not line:
            continue
        m = re.match(r'^(\d{2,3})\.\s+(.*)', line)
        if m and 74 <= int(m[1]) <= 100:
            cur, opt = int(m[1]), None
            found[cur] = {'q': m[2], 'o': {}}
        elif cur is None:
            continue
        elif line in ('Α', 'Β', 'Γ', 'Δ', 'A', 'B'):
            opt = {'A': 'Α', 'B': 'Β'}.get(line, line)
            found[cur]['o'][opt] = ''
        elif opt:
            found[cur]['o'][opt] += ' ' + line
        else:
            found[cur]['q'] += ' ' + line
    assert sorted(found) == list(range(74, 101))
    return found


def crop_verbal(doc, out):
    done = set()
    for page in list(doc)[1:4]:
        for table in page.find_tables(strategy='lines').tables:
            label = (table.extract()[0][0] or '').strip()
            if table.row_count != 5 or not re.fullmatch(r'\d{1,2}', label):
                continue
            x0, y0, x1, y1 = table.bbox
            top = next(c for c in table.rows[1].cells if c)[1]
            pix = page.get_pixmap(matrix=fitz.Matrix(4, 4), clip=fitz.Rect(x0 - 1.5, top - 1.5, x1 + 1.5, y1 + 1.5), alpha=False)
            img = Image.open(io.BytesIO(pix.tobytes('png'))).convert('L')
            img.quantize(16).save(out / f'q{label}.png', optimize=True)
            done.add(int(label))
    assert done == set(range(1, 35)), sorted(set(range(1, 35)) - done)


